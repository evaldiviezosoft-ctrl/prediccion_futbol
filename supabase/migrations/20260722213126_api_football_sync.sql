insert into public.competition_seasons (
  competition_id,
  season,
  availability_status,
  last_synced_at
)
select distinct
  c.id,
  f.season,
  'available',
  now()
from public.fixtures as f
join public.competitions as c on c.api_league_id = f.league_id
on conflict (competition_id, season) do nothing;

