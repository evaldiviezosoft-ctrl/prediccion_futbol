create function public.sync_fixture_compatibility()
returns trigger
language plpgsql
security invoker
set search_path = pg_catalog
as $$
begin
  if tg_op = 'INSERT' then
    new.id := coalesce(new.id, new.api_fixture_id);
    new.api_fixture_id := coalesce(new.api_fixture_id, new.id);

    if new.competition_id is null and new.league_id is not null then
      select c.id
      into new.competition_id
      from public.competitions as c
      where c.api_league_id = new.league_id;
    end if;

    if new.league_id is null and new.competition_id is not null then
      select l.id
      into new.league_id
      from public.competitions as c
      join public.leagues as l on l.id = c.api_league_id
      where c.id = new.competition_id;
    end if;

    new.kickoff := coalesce(new.kickoff, new.fixture_date_utc);
    new.fixture_date_utc := coalesce(new.fixture_date_utc, new.kickoff);

    if new.home_team_ref_id is null and new.home_team_id is not null then
      select t.id into new.home_team_ref_id
      from public.teams as t
      where t.api_team_id = new.home_team_id;
    elsif new.home_team_id is null and new.home_team_ref_id is not null then
      select t.api_team_id into new.home_team_id
      from public.teams as t
      where t.id = new.home_team_ref_id;
    end if;

    if new.away_team_ref_id is null and new.away_team_id is not null then
      select t.id into new.away_team_ref_id
      from public.teams as t
      where t.api_team_id = new.away_team_id;
    elsif new.away_team_id is null and new.away_team_ref_id is not null then
      select t.api_team_id into new.away_team_id
      from public.teams as t
      where t.id = new.away_team_ref_id;
    end if;

    if new.winner_team_ref_id is null and new.winner_team_id is not null then
      select t.id into new.winner_team_ref_id
      from public.teams as t
      where t.api_team_id = new.winner_team_id;
    elsif new.winner_team_id is null and new.winner_team_ref_id is not null then
      select t.api_team_id into new.winner_team_id
      from public.teams as t
      where t.id = new.winner_team_ref_id;
    end if;

    if new.raw_json = '{}'::jsonb and new.raw_payload <> '{}'::jsonb then
      new.raw_json := new.raw_payload;
    elsif new.raw_payload = '{}'::jsonb and new.raw_json <> '{}'::jsonb then
      new.raw_payload := new.raw_json;
    elsif new.raw_json <> new.raw_payload then
      new.raw_payload := new.raw_json;
    end if;
  else
    if new.id is distinct from old.id or new.api_fixture_id is distinct from old.api_fixture_id then
      raise exception 'Fixture identifiers are immutable';
    end if;

    if new.competition_id is distinct from old.competition_id then
      select l.id
      into new.league_id
      from public.competitions as c
      join public.leagues as l on l.id = c.api_league_id
      where c.id = new.competition_id;
    elsif new.league_id is distinct from old.league_id and new.league_id is not null then
      select c.id
      into new.competition_id
      from public.competitions as c
      where c.api_league_id = new.league_id;
    end if;

    if new.fixture_date_utc is distinct from old.fixture_date_utc then
      new.kickoff := new.fixture_date_utc;
    elsif new.kickoff is distinct from old.kickoff then
      new.fixture_date_utc := new.kickoff;
    end if;

    if new.home_team_id is distinct from old.home_team_id then
      select t.id into new.home_team_ref_id
      from public.teams as t
      where t.api_team_id = new.home_team_id;
    elsif new.home_team_ref_id is distinct from old.home_team_ref_id then
      select t.api_team_id into new.home_team_id
      from public.teams as t
      where t.id = new.home_team_ref_id;
    end if;

    if new.away_team_id is distinct from old.away_team_id then
      select t.id into new.away_team_ref_id
      from public.teams as t
      where t.api_team_id = new.away_team_id;
    elsif new.away_team_ref_id is distinct from old.away_team_ref_id then
      select t.api_team_id into new.away_team_id
      from public.teams as t
      where t.id = new.away_team_ref_id;
    end if;

    if new.winner_team_id is distinct from old.winner_team_id then
      select t.id into new.winner_team_ref_id
      from public.teams as t
      where t.api_team_id = new.winner_team_id;
    elsif new.winner_team_ref_id is distinct from old.winner_team_ref_id then
      select t.api_team_id into new.winner_team_id
      from public.teams as t
      where t.id = new.winner_team_ref_id;
    end if;

    if new.raw_json is distinct from old.raw_json then
      new.raw_payload := new.raw_json;
    elsif new.raw_payload is distinct from old.raw_payload then
      new.raw_json := new.raw_payload;
    end if;
  end if;

  new.fixture_date_lima := new.fixture_date_utc at time zone 'America/Lima';
  new."timestamp" := floor(extract(epoch from new.fixture_date_utc))::bigint;
  return new;
end;
$$;

create trigger fixtures_sync_compatibility
before insert or update on public.fixtures
for each row execute function public.sync_fixture_compatibility();

