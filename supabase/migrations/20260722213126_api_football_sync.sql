-- Existing fixture team ids are API-Football ids. Seed matching surrogate rows so
-- adding normalized foreign keys does not rewrite or invalidate existing fixtures.
insert into public.teams (id, api_team_id, name)
select
  source.api_team_id,
  source.api_team_id,
  max(source.team_name)
from (
  select home_team_id as api_team_id, home_team_name as team_name
  from public.fixtures
  union all
  select away_team_id as api_team_id, away_team_name as team_name
  from public.fixtures
) as source
group by source.api_team_id;

select pg_catalog.setval(
  pg_catalog.pg_get_serial_sequence('public.teams', 'id'),
  greatest(coalesce((select max(id) from public.teams), 1), 1),
  exists (select 1 from public.teams)
);

