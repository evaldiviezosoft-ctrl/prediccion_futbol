-- API-Football v3 normalized ingestion schema.
--
-- Compatibility contract:
--   * public.fixtures.id remains the API-Football fixture id and the primary key.
--   * Existing foreign keys from predictions and prediction_versions are untouched.
--   * Legacy fixtures.league_id/kickoff/raw_payload remain available.
--   * New ingestion code should upsert fixtures on api_fixture_id.

create table public.competitions (
  id bigint generated by default as identity primary key,
  api_league_id bigint unique,
  internal_code text not null unique,
  name text not null,
  country text not null,
  competition_type text not null,
  logo_url text,
  enabled boolean not null default true,
  last_synced_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint competitions_api_league_id_positive check (
    api_league_id is null or api_league_id > 0
  ),
  constraint competitions_internal_code_not_blank check (btrim(internal_code) <> ''),
  constraint competitions_name_not_blank check (btrim(name) <> ''),
  constraint competitions_country_not_blank check (btrim(country) <> ''),
  constraint competitions_type_valid check (competition_type in ('league', 'cup'))
);

-- Preserve the five existing European competitions while adopting stable internal codes.
insert into public.competitions (
  id,
  api_league_id,
  internal_code,
  name,
  country,
  competition_type,
  enabled,
  created_at,
  updated_at
)
select
  l.id,
  l.id,
  case l.id
    when 39 then 'premier_league'
    when 61 then 'ligue_1'
    when 78 then 'bundesliga'
    when 135 then 'serie_a_italy'
    when 140 then 'laliga'
    else 'legacy_league_' || l.id::text
  end,
  l.name,
  l.country,
  'league',
  l.enabled,
  l.created_at,
  l.updated_at
from public.leagues as l;

select pg_catalog.setval(
  pg_catalog.pg_get_serial_sequence('public.competitions', 'id'),
  greatest(coalesce((select max(id) from public.competitions), 1), 1),
  exists (select 1 from public.competitions)
);

